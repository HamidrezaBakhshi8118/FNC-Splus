"""Generate editor-visible methods from the committed official RPC catalog."""
import inspect
import json
from pathlib import Path
import re

from splusthon.tl.alltlobjects import tlobjects
from fnc_splus import protocol as _protocol  # noqa: F401 - register official constructor fixes

ROOT = Path(__file__).resolve().parents[1]


def method_name(name):
    return '_'.join(re.sub(r'(?<!^)(?=[A-Z])', '_', part).lower() for part in name.split('.'))


def main():
    catalog = json.loads((ROOT / 'src/fnc_splus/contracts/splus.catalog.json').read_text('utf-8'))
    output = ['"""Generated by scripts/generate_methods.py; do not edit by hand."""',
              'from typing import Any', '', '', 'class NativeMethods:']
    available = 0
    for item in catalog['methods']:
        cls = tlobjects.get(int(item['constructor_id'], 16))
        if cls is None:
            item['engine_supported'] = False
            continue
        item['engine_supported'] = True
        available += 1
        params = [param for name, param in inspect.signature(cls).parameters.items() if name != 'self']
        args = []
        fields = []
        for param in params:
            default = '' if param.default is inspect.Parameter.empty else '=' + repr(param.default)
            args.append(f'{param.name}: Any{default}')
            fields.append(f'{param.name!r}: {param.name}')
        signature = ', '.join(['self', '*', *args, 'wait: bool=True', 'timeout: float | None=30'])
        name = method_name(item['name'])
        output.extend([
            f'    async def {name}({signature}):',
            f'        """{item["name"]}: {item["operation_kind"]}; official schema, not necessarily live-tested."""',
            f'        return await self.invoke({item["name"]!r}, wait=wait, timeout=timeout,',
            '                                 **{' + ', '.join(fields) + '})', '',
        ])
    (ROOT / 'src/fnc_splus/methods.py').write_text('\n'.join(output), 'utf-8')
    # Concrete sync methods keep Pylance completion equivalent to the async API.
    from fnc_splus.client import Client
    sync = ['"""Generated synchronous API signatures."""', 'from typing import Any',
            '', '', 'class SyncMethods:']
    names = [method_name(item['name']) for item in catalog['methods'] if item['engine_supported']]
    names += ['invoke', 'send', 'send_message', 'get_me', 'get_messages', 'get_message', 'get_chats',
              'download', 'download_media', 'forward_message', 'send_file', 'send_photo', 'send_video',
              'send_voice', 'send_poll', 'get_operation', 'wait_operation', 'run', 'export_session']
    for name in names:
        function = getattr(Client, name)
        params = list(inspect.signature(function).parameters.values())[1:]
        declarations, calls, inserted_star = ['self'], [], False
        for param in params:
            if param.kind == inspect.Parameter.KEYWORD_ONLY and not inserted_star:
                declarations.append('*')
                inserted_star = True
            if param.kind == inspect.Parameter.VAR_KEYWORD:
                declarations.append('**' + param.name)
                calls.append('**' + param.name)
            else:
                default = '' if param.default is inspect.Parameter.empty else '=' + repr(param.default)
                declarations.append(f'{param.name}: Any{default}')
                calls.append(f'{param.name}={param.name}')
        sync.extend([f'    def {name}({", ".join(declarations)}):',
                     f'        return self._run(self._client.{name}({", ".join(calls)}))', ''])
    (ROOT / 'src/fnc_splus/sync_methods.py').write_text('\n'.join(sync), 'utf-8')
    (ROOT / 'src/fnc_splus/contracts/splus.catalog.json').write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2) + '\n', 'utf-8')
    print(f'Generated {available} methods from {len(catalog["methods"])} source-discovered RPCs')


if __name__ == '__main__':
    main()
